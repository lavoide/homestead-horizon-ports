// Emojiful 4.2.0 (HorizonStudio, MIT): EmojiFontRenderer.getEmojiFormattedString, for chat lines.
// Each `:short_name:` of a Twemoji emoji becomes that emoji's glyph character, drawn by the
// Emojiful resource pack's bitmap font (`packs/emojiful`, made by `tools/emojiful_port.py` with
// this table). Emojiful draws the image untinted and without a shadow: the glyph's span is white
// with shadow colour 0. The message itself is unchanged; only the line shown is.
use super::*;

fn lookup(name: &str) -> Option<char> {
    EMOJI
        .binary_search_by(|(n, _)| (*n).cmp(name))
        .ok()
        .map(|i| EMOJI[i].1)
}

fn name_char(c: char) -> bool {
    c.is_ascii_lowercase() || c.is_ascii_digit() || matches!(c, '_' | '-' | '+')
}

/// `text` cut into plain runs and emoji glyphs; None when it holds no known `:name:`.
fn segments(text: &str) -> Option<Vec<(String, bool)>> {
    if !text.contains(':') {
        return None;
    }
    let mut out: Vec<(String, bool)> = Vec::new();
    let mut plain = String::new();
    let mut found = false;
    let mut rest = text;
    while let Some(i) = rest.find(':') {
        plain.push_str(&rest[..i]);
        let after = &rest[i + 1..];
        let end = after.find(|c: char| !name_char(c));
        let emoji = match end {
            Some(e) if e > 0 && after[e..].starts_with(':') => lookup(&after[..e]).map(|c| (c, e)),
            _ => None,
        };
        match emoji {
            Some((c, e)) => {
                if !plain.is_empty() {
                    out.push((std::mem::take(&mut plain), false));
                }
                out.push((c.to_string(), true));
                found = true;
                rest = &after[e + 1..];
            }
            None => {
                plain.push(':');
                rest = after;
            }
        }
    }
    plain.push_str(rest);
    if !plain.is_empty() {
        out.push((plain, false));
    }
    found.then_some(out)
}

/// The message with its emoji codes drawn as emoji; None when it has none.
pub(super) fn convert(message: &Message) -> Option<Message> {
    let mut spans = Vec::new();
    let mut found = false;
    for span in &message.content.spans {
        match segments(&span.text) {
            None => spans.push(span.clone()),
            Some(parts) => {
                found = true;
                for (text, emoji) in parts {
                    let mut style = span.style.clone();
                    if emoji {
                        style.color = Some(0xFFFFFF);
                        style.shadow_color = Some(0);
                        style.obfuscated = None;
                    }
                    spans.push(crate::text::Span { text, style });
                }
            }
        }
    }
    if !found {
        return None;
    }
    let mut out = message.clone();
    out.content.spans = spans;
    Some(out)
}

/// A re-entered `update_command_info` (the wrapper calls it) runs as the game's own.
static UPDATING: std::sync::atomic::AtomicBool = std::sync::atomic::AtomicBool::new(false);

/// EmojiSuggestionHelper: the chat box's own update, then, for a word at the cursor that starts
/// with `:` and has two more characters, every `:name:` it begins, shown at once.
pub(super) fn update(screen: &mut ChatScreen, m: &Measure, c: &Commands) -> core::ops::ControlFlow<()> {
    use std::sync::atomic::Ordering;
    if UPDATING.swap(true, Ordering::Relaxed) {
        return core::ops::ControlFlow::Continue(());
    }
    screen.update_command_info(m, c);
    UPDATING.store(false, Ordering::Relaxed);
    suggest(screen, m);
    core::ops::ControlFlow::Break(())
}

fn suggest(screen: &mut ChatScreen, m: &Measure) {
    let value = screen.input.value.clone();
    if value.starts_with('/') || screen.layout.commands_only {
        return;
    }
    let cursor = byte_at(&value, screen.input.cursor);
    let partial = &value[..cursor];
    let start = last_word_index(partial);
    let word = partial[start..].to_lowercase();
    if !word.starts_with(':') || word.chars().count() < 3 || (word.len() > 1 && word.ends_with(':')) {
        return;
    }
    let list: Vec<Suggestion> = EMOJI
        .iter()
        .map(|(n, _)| format!(":{n}:"))
        .filter(|s| s.starts_with(&word))
        .map(|text| Suggestion {
            range: (start, cursor),
            text,
            tooltip: None,
            int_value: None,
        })
        .collect();
    if list.is_empty() {
        return;
    }
    screen.pending = Some((start, list));
    screen.show_suggestions(m, false);
}

